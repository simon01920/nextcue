def _coords(g: Graph, space: str = "Object"):
    """Texture coordinates in metres. Every mesh is authored in millimetres
    (object scale 0.001) and all pattern scales below are tuned in metres."""
    out = g.add("ShaderNodeTexCoord").outputs[space]
    if space != "Object":
        return out
    s = g.add("ShaderNodeVectorMath", operation="SCALE")
    g.link(out, s.inputs[0])
    s.inputs["Scale"].default_value = MM
    return s.outputs[0]


def _noise(g: Graph, vector, scale: float, detail: float = 4.0, rough: float = 0.55,
           distortion: float = 0.0, w: float | None = None):
    n = g.add("ShaderNodeTexNoise", inputs={"Scale": scale, "Detail": detail,
                                            "Roughness": rough, "Distortion": distortion})
    if w is not None:
        n.noise_dimensions = "4D"
        n.inputs["W"].default_value = w
    g.link(vector, n.inputs["Vector"])
    return n


def _bump(g: Graph, height, strength: float, distance: float = 0.0005, normal=None):
    b = g.add("ShaderNodeBump", inputs={"Strength": strength, "Distance": distance})
    g.link(height, b.inputs["Height"])
    if normal is not None:
        g.link(normal, b.inputs["Normal"])
    return b.outputs[0]


def _scratches(g: Graph, vector, scale: float = 60.0, density: float = 0.985):
    """Fine directional scratches: stretched noise thresholded to thin lines."""
    mapping = g.add("ShaderNodeMapping", inputs={"Scale": (scale, scale * 0.04, scale)})
    g.link(vector, mapping.inputs["Vector"])
    n = g.add("ShaderNodeTexNoise", inputs={"Scale": 1.0, "Detail": 2.0, "Roughness": 0.5})
    g.link(mapping.outputs[0], n.inputs["Vector"])
    line = g.math("GREATER_THAN", n.outputs["Fac"], density)
    return line


