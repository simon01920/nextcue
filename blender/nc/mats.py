def mode_group() -> bpy.types.ShaderNodeTree:
    grp = bpy.data.node_groups.get("NC_Mode")
    if grp is not None:
        return grp
    grp = bpy.data.node_groups.new("NC_Mode", "ShaderNodeTree")
    out = grp.nodes.new("NodeGroupOutput")
    # grid: showcase renders draw each object's art from one cell of the
    # NC_SAMPLE_SPINES grid (picked by the object's random value)
    for i, key in enumerate(("mode", "uvset", "grid")):
        grp.interface.new_socket(key, in_out="OUTPUT", socket_type="NodeSocketFloat")
        v = grp.nodes.new("ShaderNodeValue")
        v.name = v.label = key
        grp.links.new(v.outputs[0], out.inputs[i])
    return grp


def set_mode(mode: int, uvset: int = 0, grid: bool = False) -> None:
    grp = mode_group()
    grp.nodes["mode"].outputs[0].default_value = float(mode)
    grp.nodes["uvset"].outputs[0].default_value = float(uvset)
    grp.nodes["grid"].outputs[0].default_value = 1.0 if grid else 0.0
    # Nudge Cycles to recompile shaders that depend on the group.
    for mat in bpy.data.materials:
        if mat.node_tree is not None:
            mat.node_tree.update_tag()


def _mode_sockets(g: Graph):
    n = g.add("ShaderNodeGroup")
    n.node_tree = mode_group()
    is_d = g.math("COMPARE", n.outputs["mode"], float(MODE_LABEL_LIGHT))
    is_uv = g.math("COMPARE", n.outputs["mode"], float(MODE_UV))
    return n, is_d, is_uv


def _camera_like(g: Graph):
    """1 for camera rays and for camera rays that were only refracted (seen
    through a clear film), 0 for bounce/shadow rays."""
    lp = g.add("ShaderNodeLightPath")
    no_diffuse = g.math("LESS_THAN", lp.outputs["Diffuse Depth"], 0.5)
    no_glossy = g.math("LESS_THAN", lp.outputs["Glossy Depth"], 0.5)
    refracted = g.math("MULTIPLY", lp.outputs["Is Transmission Ray"], g.math("MULTIPLY", no_diffuse, no_glossy))
    return g.math("MAXIMUM", lp.outputs["Is Camera Ray"], refracted)


def _finish(g: Graph, beauty, *, label: bool, clear: bool = False, white=None, uv_maps=None,
            bounce_color=(0.35, 0.35, 0.35, 1), showcase=None, d_transmit: float = 1.0):
    """Wrap a beauty shader with the D/UV pass behaviour and connect output.

    clear=True marks transparent materials (windows, films): in the D and UV
    passes they turn transparent so labels behind them still register. The
    D pass is dimmed by d_transmit (what the film lets through); the UV pass
    must stay exactly white or it would scale the coordinates.
    """
    mode, is_d, is_uv = _mode_sockets(g)
    cam = _camera_like(g)
    if clear:
        see_through = g.add("ShaderNodeBsdfTransparent").outputs[0]
        dimmed = g.add("ShaderNodeBsdfTransparent",
                       inputs={"Color": (d_transmit, d_transmit, d_transmit, 1.0)}).outputs[0]
        m1 = g.mix_shader(is_d, beauty, dimmed)
        m2 = g.mix_shader(is_uv, m1, see_through)
        out = g.add("ShaderNodeOutputMaterial")
        g.link(m2, out.inputs["Surface"])
        return out
    if label:
        bounce = g.add("ShaderNodeBsdfDiffuse", inputs={"Color": bounce_color}).outputs[0]
        # beauty: camera sees black ink + coat; bounces see an average print.
        beauty_out = g.mix_shader(cam, bounce, beauty)
        d_white = white or g.add("ShaderNodeBsdfDiffuse", inputs={"Color": (1, 1, 1, 1)}).outputs[0]
        d_out = g.mix_shader(cam, bounce, d_white)
        hero = g.add("ShaderNodeUVMap", uv_map=(uv_maps or {}).get("hero", LABEL_UV_HERO))
        spine = g.add("ShaderNodeUVMap", uv_map=(uv_maps or {}).get("spine", LABEL_UV_SPINE))
        uv = g.add("ShaderNodeMix", data_type="VECTOR")
        g.link(mode.outputs["uvset"], uv.inputs[0])
        g.link(hero.outputs[0], uv.inputs[4])
        g.link(spine.outputs[0], uv.inputs[5])
        sep = g.add("ShaderNodeSeparateXYZ")
        g.link(uv.outputs[1], sep.inputs[0])
        comb = g.add("ShaderNodeCombineColor")
        g.link(sep.outputs[0], comb.inputs[0])
        g.link(sep.outputs[1], comb.inputs[1])
        comb.inputs[2].default_value = 1.0
        uv_out = g.add("ShaderNodeEmission", inputs={"Color": comb.outputs[0], "Strength": 1.0}).outputs[0]
    else:
        black = g.add("ShaderNodeEmission", inputs={"Color": (0, 0, 0, 1), "Strength": 0.0}).outputs[0]
        beauty_out = beauty
        d_out = g.mix_shader(cam, beauty, black)
        uv_out = black
    m1 = g.mix_shader(is_d, beauty_out, d_out)
    m2 = g.mix_shader(is_uv, m1, uv_out)
    final = m2
    if label and showcase is not None:
        is_show = g.math("COMPARE", mode.outputs["mode"], float(MODE_SHOWCASE))
        final = g.mix_shader(is_show, m2, showcase)
    out = g.add("ShaderNodeOutputMaterial")
    g.link(final, out.inputs["Surface"])
    return out


