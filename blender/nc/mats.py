"""Procedural, physically based materials and the render-pass switch.

Every material reads the shared node group ``NC_Mode`` so one scene renders
three ways without swapping material slots:

* mode 0 — beauty. Label surfaces (artwork swapped at runtime) render as
  black ink under their real coat, so the plate carries only their gloss.
* mode 1 — label light ``D``. Label surfaces render white-diffuse; every
  other surface is black to the camera but keeps its real shading for
  bounce rays, so the label lighting matches the beauty pass.
* mode 2 — UV. Label surfaces emit (U, V, 1) from the chosen label UV map;
  everything else emits black. Rendered unfiltered, one sample.

``NC_Mode`` has a second output, ``uvset``: 0 selects ``UV_LABEL_HERO``
(the full artwork atlas), 1 selects ``UV_LABEL_SPINE`` (spine-only atlas
used by the shelf plates).
"""

from __future__ import annotations

from dataclasses import dataclass

import bpy

from . import MM

LABEL_UV_HERO = "UV_LABEL_HERO"
LABEL_UV_SPINE = "UV_LABEL_SPINE"
BAKE_UV = "UV_BAKE"

MODE_BEAUTY, MODE_LABEL_LIGHT, MODE_UV, MODE_SHOWCASE = 0, 1, 2, 3

# Sample artwork shown on label surfaces in showcase mode (portfolio
# renders, GLB previews). Generated by nc/artwork.py; a cream placeholder
# is used until it exists.
SAMPLE_HERO_IMAGE = "NC_SAMPLE_HERO"


def sample_image(name: str = SAMPLE_HERO_IMAGE) -> bpy.types.Image:
    img = bpy.data.images.get(name)
    if img is None:
        img = bpy.data.images.new(name, 64, 64, alpha=False)
        img.generated_color = (0.86, 0.84, 0.79, 1.0)
    return img


def load_sample_image(path, name: str = SAMPLE_HERO_IMAGE) -> bpy.types.Image | None:
    """Use an atlas image file as the showcase artwork (call before
    building label materials)."""
    from pathlib import Path
    from .paths import ROOT
    p = Path(path)
    if not p.is_absolute():
        p = (ROOT / p).resolve()   # bpy.data.images.load ignores the process CWD
    if not p.exists():
        return None
    old = bpy.data.images.get(name)
    if old is not None:
        bpy.data.images.remove(old)
    img = bpy.data.images.load(str(p), check_existing=False)
    img.name = name
    img.colorspace_settings.name = "sRGB"
    return img


# --------------------------------------------------------------------------
# Small node-graph builder
# --------------------------------------------------------------------------

class Graph:
    def __init__(self, tree: bpy.types.NodeTree):
        self.tree = tree
        self.nodes = tree.nodes
        self.links = tree.links
        self._x = 0

    def add(self, bl_type: str, *, inputs: dict | None = None, **props):
        n = self.nodes.new(bl_type)
        n.location = (self._x, 0)
        self._x += 220
        for k, v in props.items():
            setattr(n, k, v)
        for k, v in (inputs or {}).items():
            sock = n.inputs[k]
            if isinstance(v, bpy.types.NodeSocket):
                self.links.new(v, sock)
            else:
                sock.default_value = v
        return n

    def link(self, out_sock, in_sock):
        self.links.new(out_sock, in_sock)

    # math helpers ---------------------------------------------------------
    def math(self, op: str, a, b=0.0, c=0.0, *, clamp=False):
        n = self.add("ShaderNodeMath", operation=op, use_clamp=clamp)
        for i, v in enumerate((a, b, c)):
            if isinstance(v, bpy.types.NodeSocket):
                self.link(v, n.inputs[i])
            else:
                n.inputs[i].default_value = v
        return n.outputs[0]

    def mix_color(self, fac, a, b, blend: str = "MIX"):
        n = self.add("ShaderNodeMix", data_type="RGBA", blend_type=blend)
        for sock, v in ((n.inputs[0], fac), (n.inputs[6], a), (n.inputs[7], b)):
            if isinstance(v, bpy.types.NodeSocket):
                self.link(v, sock)
            else:
                sock.default_value = v if not isinstance(v, (int, float)) or sock.type != "RGBA" else (v, v, v, 1)
        return n.outputs[2]

    def mix_float(self, fac, a, b):
        n = self.add("ShaderNodeMix", data_type="FLOAT")
        for sock, v in ((n.inputs[0], fac), (n.inputs[2], a), (n.inputs[3], b)):
            if isinstance(v, bpy.types.NodeSocket):
                self.link(v, sock)
            else:
                sock.default_value = v
        return n.outputs[0]

    def mix_shader(self, fac, a, b):
        n = self.add("ShaderNodeMixShader")
        if isinstance(fac, bpy.types.NodeSocket):
            self.link(fac, n.inputs[0])
        else:
            n.inputs[0].default_value = fac
        self.link(a, n.inputs[1])
        self.link(b, n.inputs[2])
        return n.outputs[0]

    def ramp(self, fac, stops):
        """stops: [(pos, (r,g,b,a)), ...]"""
        n = self.add("ShaderNodeValToRGB")
        self.link(fac, n.inputs[0])
        el = n.color_ramp.elements
        while len(el) > len(stops):
            el.remove(el[-1])
        while len(el) < len(stops):
            el.new(0.5)
        for e, (pos, col) in zip(el, stops):
            e.position = pos
            e.color = col if len(col) == 4 else (*col, 1.0)
        return n.outputs[0]


def _new_material(name: str) -> tuple[bpy.types.Material, Graph]:
    # Never delete an existing material of the same name: objects built
    # earlier may still use it. Callers that need one shared instance (or an
    # exact name, e.g. GLB material slots) go through `cached`.
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    mat.node_tree.nodes.clear()
    return mat, Graph(mat.node_tree)


def cached(name: str, factory) -> bpy.types.Material:
    """Return the scene's material `name`, building it with factory() once."""
    mat = bpy.data.materials.get(name)
    return mat if mat is not None else factory()


