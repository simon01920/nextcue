@dataclass
class Plastic:
    color: tuple = (0.010, 0.010, 0.011, 1.0)
    roughness: float = 0.38
    rough_var: float = 0.10
    stipple: float = 0.0       # molded micro-texture bump strength
    scratch: float = 0.25      # scratch visibility 0..1
    seed: float = 0.0


def plastic(name: str, p: Plastic = Plastic()) -> bpy.types.Material:
    """Injection-moulded ABS: near-black base, roughness breakup, fine
    stipple and handling scratches that read as edge highlights."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    rough_noise = _noise(g, co, 180.0, 6.0, 0.6, w=p.seed)
    rough = g.math("MULTIPLY_ADD", rough_noise.outputs["Fac"], p.rough_var * 2, p.roughness - p.rough_var)
    scratch = _scratches(g, co, 90.0)
    scratch_amt = g.math("MULTIPLY", scratch, p.scratch)
    rough = g.math("SUBTRACT", rough, g.math("MULTIPLY", scratch_amt, 0.18), clamp=True)
    normal = None
    if p.stipple > 0:
        st = _noise(g, co, 2600.0, 2.0, 0.5, w=p.seed + 3)
        normal = _bump(g, st.outputs["Fac"], p.stipple, 0.00004)
    sc_bump = _bump(g, scratch_amt, 0.25, 0.00002, normal)
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": p.color, "Roughness": rough, "Normal": sc_bump,
        "Specular IOR Level": 0.5, "IOR": 1.53,
    })
    _finish(g, bsdf.outputs[0], label=False)
    return mat


def clear_plastic(name: str, tint=(0.92, 0.94, 0.95, 1.0), roughness: float = 0.03,
                  dust: float = 0.35) -> bpy.types.Material:
    """Window polycarbonate/acrylic with a little dust and scratching."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    d = _noise(g, co, 900.0, 3.0, 0.7)
    dust_mask = g.math("POWER", d.outputs["Fac"], 6.0)
    rough = g.math("MULTIPLY_ADD", dust_mask, dust * 0.5, roughness)
    sc = _scratches(g, co, 140.0, 0.992)
    rough = g.math("MAXIMUM", rough, g.math("MULTIPLY", sc, 0.25))
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": tint, "Roughness": rough, "Transmission Weight": 1.0,
        "IOR": 1.52, "Specular IOR Level": 0.5,
    })
    # Thin panes: let shadow rays through. With refractive caustics off,
    # Cycles would otherwise treat the glass as opaque for direct light and
    # leave everything behind it black.
    lp = g.add("ShaderNodeLightPath")
    passthru = g.add("ShaderNodeBsdfTransparent", inputs={"Color": tint}).outputs[0]
    shaded = g.mix_shader(lp.outputs["Is Shadow Ray"], bsdf.outputs[0], passthru)
    _finish(g, shaded, label=False, clear=True)
    mat["nc_clear"] = {"tint": list(tint), "roughness": roughness}
    return mat


def film(name: str, *, crinkle: float = 1.0, transmit: float = 0.93) -> bpy.types.Material:
    """Shrink-wrap: a thin film is not a refracting slab, so the camera ray
    passes straight through (Transparent BSDF) and only a Fresnel-weighted
    glossy layer is added. Crinkles are sharp Voronoi creases plus soft
    waviness, strongest near the heat-sealed ends (object |Z| large)."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    sep = g.add("ShaderNodeSeparateXYZ")
    g.link(co, sep.inputs[0])
    # ends of the sleeve sit at |z| ~ 95 mm in object space (metres * 1000)
    end_w = g.math("POWER", g.math("MULTIPLY", g.math("ABSOLUTE", sep.outputs[2]), 1.0 / 0.0955, clamp=True), 10.0)
    vor = g.add("ShaderNodeTexVoronoi", feature="DISTANCE_TO_EDGE", inputs={"Scale": 70.0})
    warp = _noise(g, co, 60.0, 3.0, 0.5, distortion=1.2)
    wmix = g.add("ShaderNodeMix", data_type="VECTOR")
    wmix.inputs[0].default_value = 0.004
    g.link(co, wmix.inputs[4])
    g.link(warp.outputs["Color"], wmix.inputs[5])
    g.link(wmix.outputs[1], vor.inputs["Vector"])
    # soft-edged creases: a smooth ridge profile instead of a hard line
    crease = g.math("POWER", g.math("SUBTRACT", 1.0, g.math("MULTIPLY", vor.outputs["Distance"], 3.0,
                                                            clamp=True)), 3.0)
    crease_w = g.math("MULTIPLY_ADD", end_w, 0.6, 0.1)
    soft = _noise(g, co, 35.0, 2.0, 0.4)
    height = g.math("MULTIPLY_ADD", g.math("MULTIPLY", crease, crease_w), crinkle,
                    g.math("MULTIPLY", soft.outputs["Fac"], 0.6 * crinkle))
    nrm = _bump(g, height, 0.12, 0.0002)
    fres = g.add("ShaderNodeFresnel", inputs={"IOR": 1.5})
    g.link(nrm, fres.inputs["Normal"])
    gloss = g.add("ShaderNodeBsdfGlossy", inputs={"Roughness": 0.04, "Color": (1, 1, 1, 1)})
    g.link(nrm, gloss.inputs["Normal"])
    thru = g.add("ShaderNodeBsdfTransparent", inputs={"Color": (transmit, transmit, transmit, 1.0)})
    # both film surfaces reflect: roughly double the single-surface Fresnel
    f2 = g.math("MULTIPLY", fres.outputs[0], 1.8, clamp=True)
    shaded = g.mix_shader(f2, thru.outputs[0], gloss.outputs[0])
    _finish(g, shaded, label=False, clear=True, d_transmit=transmit)
    mat["nc_clear"] = {"tint": [transmit, transmit, transmit, 1.0], "roughness": 0.04, "film": True}
    return mat


def tape_pack(name: str) -> bpy.types.Material:
    """Wound magnetic tape: dark brown oxide, glossy edges with concentric
    winding rings centred on each reel object's origin."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    sep = g.add("ShaderNodeSeparateXYZ")
    g.link(co, sep.inputs[0])
    r = g.math("SQRT", g.math("ADD", g.math("MULTIPLY", sep.outputs[0], sep.outputs[0]),
                              g.math("MULTIPLY", sep.outputs[1], sep.outputs[1])))
    rings = g.math("SINE", g.math("MULTIPLY", r, 14000.0))
    fine = g.math("SINE", g.math("MULTIPLY", r, 61000.0))
    wobble = _noise(g, co, 400.0, 2.0, 0.5)
    rings_mix = g.math("ADD", g.math("MULTIPLY", rings, 0.6), g.math("MULTIPLY", fine, 0.4))
    shade = g.math("MULTIPLY_ADD", wobble.outputs["Fac"], 0.25, g.math("MULTIPLY_ADD", rings_mix, 0.08, 0.5))
    col = g.ramp(shade, [(0.0, (0.020, 0.012, 0.008)), (1.0, (0.060, 0.038, 0.024))])
    nrm = _bump(g, rings_mix, 0.08, 0.00003)
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": col, "Roughness": 0.22, "Normal": nrm, "Specular IOR Level": 0.6,
        "Anisotropic": 0.6,
    })
    tangent = g.add("ShaderNodeTangent", direction_type="RADIAL", axis="Z")
    g.link(tangent.outputs[0], bsdf.inputs["Tangent"])
    _finish(g, bsdf.outputs[0], label=False)
    return mat


def hub_plastic(name: str, color=(0.80, 0.80, 0.78, 1.0), roughness: float = 0.42) -> bpy.types.Material:
    return plastic(name, Plastic(color=color, roughness=roughness, rough_var=0.06, scratch=0.1, seed=7.0))


def metal(name: str, color=(0.72, 0.72, 0.70, 1.0), roughness: float = 0.28,
          anisotropic: float = 0.0) -> bpy.types.Material:
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    n = _noise(g, co, 3000.0, 4.0, 0.6)
    rough = g.math("MULTIPLY_ADD", n.outputs["Fac"], 0.12, roughness - 0.06)
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": color, "Metallic": 1.0, "Roughness": rough, "Anisotropic": anisotropic,
    })
    _finish(g, bsdf.outputs[0], label=False)
    return mat


def matte(name: str, color, roughness: float = 0.8, bump: float = 0.0,
          bump_scale: float = 1500.0) -> bpy.types.Material:
    """Generic rough dielectric (board interiors, felt, raw edges)."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    n = _noise(g, co, bump_scale, 6.0, 0.65)
    col = g.mix_color(g.math("MULTIPLY", n.outputs["Fac"], 0.35), color,
                      tuple(min(1.0, c * 0.8) for c in color[:3]) + (1.0,))
    nrm = _bump(g, n.outputs["Fac"], bump, 0.0002) if bump else None
    inputs = {"Base Color": col, "Roughness": roughness, "Specular IOR Level": 0.35}
    if nrm is not None:
        inputs["Normal"] = nrm
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs=inputs)
    _finish(g, bsdf.outputs[0], label=False)
    return mat


@dataclass
class Print:
    """A printed label surface whose artwork is supplied at runtime."""
    ink_roughness: float = 0.45
    coat: float = 0.55          # varnish/laminate weight (0 = bare paper)
    coat_roughness: float = 0.22
    wear: float = 0.5           # how much the coat scuffs off on edges
    dust: float = 0.0           # dust settled on up-facing print (shelf tops)
    uv_hero: str = LABEL_UV_HERO
    uv_spine: str = LABEL_UV_SPINE


def label(name: str, p: Print = Print()) -> bpy.types.Material:
    """Runtime-artwork surface (COVER_ART, LABEL_SPINE, LABEL_FRONT …).

    Beauty renders black ink under the varnish so the plate keeps only the
    gloss; the D pass renders white diffuse. Scuffed varnish near edges is
    driven by pointiness so worn corners lose their sheen."""
    mat, g = _new_material(name)
    # read by the GLB exporter, which rebuilds labels as swappable slots
    mat["nc_label"] = {"uv": p.uv_hero, "roughness": p.ink_roughness, "coat": p.coat,
                       "coat_roughness": p.coat_roughness}
    co = _coords(g, "Object")
    geo = g.add("ShaderNodeNewGeometry")
    edge = g.math("SMOOTH_MAX", g.math("MULTIPLY_ADD", geo.outputs["Pointiness"], 6.0, -3.05), 0.0, clamp=True)
    scuff_noise = _noise(g, co, 700.0, 5.0, 0.6)
    scuff = g.math("MULTIPLY", g.math("MULTIPLY", edge, scuff_noise.outputs["Fac"]), p.wear * 2.0, clamp=True)
    coat_w = g.math("MULTIPLY", g.math("SUBTRACT", 1.0, scuff, clamp=True), p.coat)
    fiber = _noise(g, co, 2200.0, 3.0, 0.5)
    nrm = _bump(g, fiber.outputs["Fac"], 0.05, 0.00002)
    ink = (0.0, 0.0, 0.0, 1.0)
    rough = p.ink_roughness
    white = None
    if p.dust > 0:
        # Dust is a layer over the print: the beauty plate gets grey fluff,
        # and the D pass is dimmed by its coverage so the art shows less.
        sepn = g.add("ShaderNodeSeparateXYZ")
        g.link(geo.outputs["Normal"], sepn.inputs[0])
        up = g.math("POWER", g.math("MAXIMUM", sepn.outputs[2], 0.0), 3.0)
        dn = _noise(g, co, 220.0, 6.0, 0.7, w=5.0)
        dust_mask = g.math("MULTIPLY", g.math("MULTIPLY", up, g.math("POWER", dn.outputs["Fac"], 1.8)),
                           p.dust * 1.8, clamp=True)
        ink = g.mix_color(dust_mask, (0.0, 0.0, 0.0, 1.0), (0.36, 0.34, 0.31, 1.0))
        rough = g.math("MULTIPLY_ADD", dust_mask, 0.5, p.ink_roughness)
        coat_w = g.math("MULTIPLY", coat_w, g.math("SUBTRACT", 1.0, dust_mask, clamp=True))
        cover = g.math("SUBTRACT", 1.0, dust_mask, clamp=True)
        white_col = g.add("ShaderNodeCombineColor")
        for i in range(3):
            g.link(cover, white_col.inputs[i])
        white = g.add("ShaderNodeBsdfDiffuse", inputs={"Color": white_col.outputs[0]}).outputs[0]
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": ink, "Roughness": rough,
        "Specular IOR Level": 0.4, "Coat Weight": coat_w, "Coat Roughness": p.coat_roughness,
        "Coat IOR": 1.5, "Normal": nrm,
    })
    # Showcase: the same print with sample artwork, for portfolio renders.
    sample_uv = g.add("ShaderNodeUVMap", uv_map=p.uv_hero)
    tex = g.add("ShaderNodeTexImage", image=sample_image(), interpolation="Cubic")
    g.link(sample_uv.outputs[0], tex.inputs["Vector"])
    # grid variant: spine UVs into one of 4x4 cells chosen per object
    info = g.add("ShaderNodeObjectInfo")
    cell = g.math("FLOOR", g.math("MULTIPLY", info.outputs["Random"], 15.999))
    cx = g.math("MULTIPLY", g.math("MODULO", cell, 4.0), 0.25)
    cy = g.math("MULTIPLY", g.math("FLOOR", g.math("MULTIPLY", cell, 0.25)), 0.25)
    suv = g.add("ShaderNodeSeparateXYZ")
    g.link(g.add("ShaderNodeUVMap", uv_map=p.uv_spine).outputs[0], suv.inputs[0])
    gu = g.math("MULTIPLY_ADD", suv.outputs[0], 0.25, cx)
    gv = g.math("MULTIPLY_ADD", suv.outputs[1], 0.25, cy)
    guv = g.add("ShaderNodeCombineXYZ")
    g.link(gu, guv.inputs[0])
    g.link(gv, guv.inputs[1])
    gtex = g.add("ShaderNodeTexImage", image=sample_image("NC_SAMPLE_SPINES"), interpolation="Cubic")
    g.link(guv.outputs[0], gtex.inputs["Vector"])
    show_col = g.mix_color(_mode_sockets(g)[0].outputs["grid"], tex.outputs["Color"], gtex.outputs["Color"])
    show = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": show_col, "Roughness": p.ink_roughness,
        "Specular IOR Level": 0.4, "Coat Weight": coat_w, "Coat Roughness": p.coat_roughness,
        "Coat IOR": 1.5, "Normal": nrm,
    })
    _finish(g, bsdf.outputs[0], label=True, uv_maps={"hero": p.uv_hero, "spine": p.uv_spine},
            showcase=show.outputs[0], white=white)
    return mat


@dataclass
class Wood:
    base: tuple = (0.18, 0.095, 0.05, 1.0)    # walnut
    dark: tuple = (0.075, 0.038, 0.020, 1.0)
    roughness: float = 0.48
    grain_scale: float = 22.0
    seed: float = 0.0
    dust: float = 0.45
    axis: str = "X"            # grain runs along this object axis


def wood(name: str, w: Wood = Wood()) -> bpy.types.Material:
    """Satin-lacquered veneer: distorted ring grain, pore streaks, colour
    variation, and dust that settles on up-facing surfaces."""
    mat, g = _new_material(name)
    co = _coords(g, "Object")
    stretch = {"X": (w.grain_scale * 0.06, w.grain_scale, w.grain_scale),
               "Y": (w.grain_scale, w.grain_scale * 0.06, w.grain_scale),
               "Z": (w.grain_scale, w.grain_scale, w.grain_scale * 0.06)}[w.axis]
    mapping = g.add("ShaderNodeMapping", inputs={"Scale": stretch, "Location": (w.seed, w.seed * 0.37, 0)})
    g.link(co, mapping.inputs["Vector"])
    warp = _noise(g, mapping.outputs[0], 2.0, 3.0, 0.5, distortion=0.4)
    wave = g.add("ShaderNodeTexWave", wave_type="RINGS", rings_direction="SPHERICAL",
                 inputs={"Scale": 1.2, "Distortion": 7.0, "Detail": 3.0, "Detail Scale": 1.4,
                         "Detail Roughness": 0.6})
    warped = g.add("ShaderNodeMix", data_type="VECTOR")
    warped.inputs[0].default_value = 0.35
    g.link(mapping.outputs[0], warped.inputs[4])
    g.link(warp.outputs["Color"], warped.inputs[5])
    g.link(warped.outputs[1], wave.inputs["Vector"])
    pores_map = g.add("ShaderNodeMapping", inputs={"Scale": tuple(s * 9 for s in stretch)})
    g.link(co, pores_map.inputs["Vector"])
    pores = _noise(g, pores_map.outputs[0], 1.0, 2.0, 0.5)
    pore_line = g.math("POWER", pores.outputs["Fac"], 3.0)
    grain = g.math("MULTIPLY_ADD", wave.outputs["Fac"], 0.75, g.math("MULTIPLY", pore_line, 0.35))
    col = g.ramp(grain, [(0.0, w.dark), (0.55, w.base), (1.0, tuple(min(1, c * 1.35) for c in w.base[:3]) + (1.0,))])
    tone = _noise(g, co, 4.0, 2.0, 0.5, w=w.seed)
    col = g.mix_color(g.math("MULTIPLY", tone.outputs["Fac"], 0.25), col, w.dark, "MULTIPLY")
    # dust on up-facing surfaces, broken up by noise
    geo = g.add("ShaderNodeNewGeometry")
    sepn = g.add("ShaderNodeSeparateXYZ")
    g.link(geo.outputs["Normal"], sepn.inputs[0])
    up = g.math("POWER", g.math("MAXIMUM", sepn.outputs[2], 0.0), 4.0)
    dn = _noise(g, co, 160.0, 6.0, 0.7, w=w.seed + 11)
    dust_mask = g.math("MULTIPLY", up, g.math("POWER", dn.outputs["Fac"], 2.5))
    dust_mask = g.math("MULTIPLY", dust_mask, w.dust * 1.6, clamp=True)
    col = g.mix_color(dust_mask, col, (0.42, 0.40, 0.37, 1.0))
    rough = g.math("MULTIPLY_ADD", dust_mask, 0.45, w.roughness)
    nrm = _bump(g, grain, 0.06, 0.0002)
    bsdf = g.add("ShaderNodeBsdfPrincipled", inputs={
        "Base Color": col, "Roughness": rough, "Normal": nrm, "Specular IOR Level": 0.45,
        "Coat Weight": g.math("MULTIPLY", g.math("SUBTRACT", 1.0, dust_mask, clamp=True), 0.35),
        "Coat Roughness": 0.3,
    })
    _finish(g, bsdf.outputs[0], label=False)
    return mat


def emission_card(name: str, strength: float, color=(1, 1, 1, 1)) -> bpy.types.Material:
    """Light card: visible only in reflections (set ray visibility on the
    object), gives product-shot gradient highlights."""
    mat, g = _new_material(name)
    em = g.add("ShaderNodeEmission", inputs={"Color": color, "Strength": strength})
    out = g.add("ShaderNodeOutputMaterial")
    g.link(em.outputs[0], out.inputs["Surface"])
    return mat
